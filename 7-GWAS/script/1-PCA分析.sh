#!/usr/bin/env bash
#===============================================================================
# 脚本：优化后的 PCA 片段（仅变量提取，功能与注释不变）
#===============================================================================

set -euo pipefail
IFS=$'\n\t'

#-------------------------------------------------------------------------------
# 定义路径和文件前缀变量
#-------------------------------------------------------------------------------
DATA_DIR="/mnt/c/Users/Administrator/Desktop/data"
CONF_DIR="/mnt/c/Users/Administrator/Desktop/conf"
PREFIX="Han_SNP4"

#-------------------------------------------------------------------------------
# 之前已经完成了质控
# 现在开始进行 PCA 分析
#-------------------------------------------------------------------------------
plink --bfile "${DATA_DIR}/${PREFIX}" \
    --pca 20 \
    --out "${DATA_DIR}/${PREFIX}"

twstats -t twtable \
    -i "${DATA_DIR}/${PREFIX}.eigenval" \
    -o "${DATA_DIR}/${PREFIX}.out"


#* 注意 .out 文件中的 p-value，一般认为 p-value 小于 0.05 表示有显著的主成分
#* 因此，针对 p-value 小于 0.05 的主成分，我们可以进行进一步的分析

